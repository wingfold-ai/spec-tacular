/**
 * Where matrices and their tests live, and writing them.
 *
 * A matrix belongs to its requirement, which outlives the change that wrote
 * it: archived, the requirement joins the baseline and its tests keep
 * running. So matrices are kept under `spec-tacular/matrix/`, not in the
 * change folder that archiving moves — tests importing them would break. They
 * are generated, never edited, and regenerated whenever the formula, the
 * glossary or the generator changes; a file that differs from what would be
 * generated now is stale.
 *
 * The runner (runners/spec-tacular-matrix.ts) is copied into the project, and
 * a table-driven test file per matrix imports it, the matrix, and the
 * harness for its component — the one part written by hand.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, relative } from 'node:path';
import { matrixConfig } from './config.ts';
import { compiledMapping, loadMapping, mappingPath } from './harness.ts';
// Embedded as text, like the schema files, so a compiled binary carries it.
// TypeScript reads a .ts import as a module; Bun's text loader gives the source.
// @ts-expect-error -- a text import of a TypeScript file
import runnerSource from '../../../runners/spec-tacular-matrix.ts' with { type: 'text' };
import { slugify, type ReviewItem } from '../requirements.ts';
import { isRisk } from '../risks.ts';
import { tagFor } from '../evidence.ts';
import { formalOf } from './formal.ts';
import type { Glossary } from './glossary.ts';
import { matricesFor, type Matrix } from './matrix.ts';

export const RUNNER_SOURCE = runnerSource as string;

export { matrixConfig, type MatrixConfig } from './config.ts';

export interface MatrixEntry {
  item: ReviewItem;
  /** Relative to the project. */
  path: string;
  matrix: Matrix;
  /** The harness module it is run through, relative to the project. */
  harness: string;
}

const json = (m: Matrix) => `${JSON.stringify(m, null, 2)}\n`;

/** Every matrix the formal items of a change give, with where it is kept. */
export function changeMatrices(
  projectRoot: string,
  change: string,
  items: ReviewItem[],
  glossary: Glossary | null,
): MatrixEntry[] {
  const config = matrixConfig(projectRoot);
  const out: MatrixEntry[] = [];
  for (const item of items) {
    const form = formalOf(item);
    if (!form) continue;
    const slug = item.id.split('#')[1] ?? slugify(item.name);
    const dir = isRisk(item) ? join('spec-tacular', 'matrix', 'risks') : join('spec-tacular', 'matrix', item.capability);
    const base = isRisk(item) ? `${change}-${slug}` : slug;
    const matrices = matricesFor(item, tagFor(change, item), form, glossary);
    matrices.forEach((m, i) => {
      // A decision's harness is its capability's; a FRETish one names its component.
      m.component = m.kind === 'fret' ? m.component : isRisk(item) ? change : item.capability;
      out.push({
        item,
        path: join(dir, `${base}${matrices.length > 1 ? `-${i + 1}` : ''}.json`),
        matrix: m,
        harness: join(config.harness, `${slugify(m.component)}.ts`),
      });
    });
  }
  return out;
}

/** Matrices whose file is missing or differs from what would be generated now. */
export function staleMatrices(projectRoot: string, entries: MatrixEntry[]): MatrixEntry[] {
  return entries.filter((e) => {
    try {
      return readFileSync(join(projectRoot, e.path), 'utf8') !== json(e.matrix);
    } catch {
      return true;
    }
  });
}

/** Writes the matrices that changed; returns their paths. */
export function writeMatrices(projectRoot: string, entries: MatrixEntry[]): string[] {
  const written: string[] = [];
  for (const e of staleMatrices(projectRoot, entries)) {
    const file = join(projectRoot, e.path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, json(e.matrix), 'utf8');
    written.push(e.path);
  }
  return written;
}

const importPath = (fromFile: string, toFile: string) => {
  const rel = relative(dirname(fromFile), toFile);
  return rel.startsWith('.') ? rel : `./${rel}`;
};

/** The table-driven test for one matrix: generated, and regenerated with it. */
export function testFileFor(projectRoot: string, e: MatrixEntry, config = matrixConfig(projectRoot)): { path: string; content: string } {
  const path = join(config.tests, e.path.replace(/^spec-tacular\/matrix\//, '').replace(/\.json$/, '.matrix.test.ts'));
  const hash = createHash('sha256').update(json(e.matrix)).digest('hex').slice(0, 16);
  const header = [
    `// Generated by spec-tacular from ${e.path} — do not edit.`,
    `// \`spec-tacular matrix --write\` regenerates it with the matrix (${hash}).`,
    `import { test } from '${config.testImport}';`,
  ];
  // A mapping is compiled in: the harness is then data, bound to the module.
  const { mapping } = loadMapping(projectRoot, mappingPath(config, slugify(e.matrix.component)));
  const content = mapping
    ? [
        ...header,
        `import { harnessFromMapping, matrixCases } from '${importPath(path, config.runner)}';`,
        `import * as code from '${importPath(path, mapping.module)}';`,
        `import matrix from '${importPath(path, e.path)}';`,
        '',
        `// From ${mappingPath(config, slugify(e.matrix.component))}.`,
        `const mapping = ${JSON.stringify(compiledMapping(mapping), null, 2)};`,
        '',
        'for (const c of matrixCases(matrix as never, harnessFromMapping(mapping as never, code as never))) test(c.name, c.run);',
        '',
      ]
    : [
        ...header,
        `import { matrixCases } from '${importPath(path, config.runner)}';`,
        `import { harness } from '${importPath(path, e.harness)}';`,
        `import matrix from '${importPath(path, e.path)}';`,
        '',
        'for (const c of matrixCases(matrix as never, harness)) test(c.name, c.run);',
        '',
      ];
  return { path, content: content.join('\n') };
}

export interface WriteTestsResult {
  runner: string;
  tests: string[];
  /** Harness modules the tests import that do not exist yet. */
  missingHarness: string[];
}

/** Copies the runner and writes a test file per matrix. */
export function writeTests(projectRoot: string, entries: MatrixEntry[]): WriteTestsResult {
  const config = matrixConfig(projectRoot);
  const runner = join(projectRoot, config.runner);
  mkdirSync(dirname(runner), { recursive: true });
  writeFileSync(runner, RUNNER_SOURCE, 'utf8');
  const tests: string[] = [];
  for (const e of entries) {
    const t = testFileFor(projectRoot, e, config);
    const file = join(projectRoot, t.path);
    mkdirSync(dirname(file), { recursive: true });
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current !== t.content) writeFileSync(file, t.content, 'utf8');
    tests.push(t.path);
  }
  // A harness is code or a mapping; either will do.
  const missingHarness = [...new Set(entries.map((e) => e.harness))].filter(
    (h) => !existsSync(join(projectRoot, h)) && !existsSync(join(projectRoot, h.replace(/\.ts$/, '.mapping.yaml'))),
  );
  return { runner: config.runner, tests, missingHarness };
}

/**
 * Removes the matrices — and their generated tests — that are no longer
 * generated: of a requirement renamed, removed or no longer formal, or a
 * matrix its item no longer has. `keep` is every matrix generated now, for
 * the active changes and the baseline alike. A risk's matrix belongs to its
 * change, and is only removed while that change is active — an archived
 * change's guard tests keep running. Returns the files removed.
 */
export function removeOrphanMatrices(
  projectRoot: string,
  keep: Set<string>,
  activeChanges: string[],
): string[] {
  const config = matrixConfig(projectRoot);
  const root = join(projectRoot, 'spec-tacular', 'matrix');
  const removed: string[] = [];
  const walk = (dir: string) => {
    for (const entry of existsSync(dir) ? readdirSync(dir, { withFileTypes: true }) : []) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(path);
        continue;
      }
      const rel = relative(projectRoot, path);
      if (!entry.name.endsWith('.json') || keep.has(rel)) continue;
      let item: unknown;
      try {
        item = (JSON.parse(readFileSync(path, 'utf8')) as { item?: unknown }).item;
      } catch {
        continue;
      }
      if (typeof item !== 'string') continue; // not one spec-tacular generated
      if (item.startsWith('risks#') && !activeChanges.some((c) => entry.name.startsWith(`${c}-`))) continue;
      rmSync(path);
      const test = join(projectRoot, config.tests, rel.replace(/^spec-tacular\/matrix\//, '').replace(/\.json$/, '.matrix.test.ts'));
      if (existsSync(test)) rmSync(test);
      removed.push(rel);
    }
  };
  walk(root);
  return removed;
}
